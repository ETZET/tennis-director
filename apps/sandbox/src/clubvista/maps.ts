/** 一排虚线（马路中线）：每 period 米一段 dash 米长 */
function dashes(id: string, x0: number, x1: number, z: number, dash: number, period: number): Strip[] {
  const out: Strip[] = [];
  for (let x = x0, i = 0; x < x1; x += period, i++)
    out.push({
      id: `${id}${i}`,
      pts: [
        [x, z],
        [x + dash, z],
      ],
      w: 0.16,
      mat: 'roadPaint',
      lift: 0.03,
    });
  return out;
}

