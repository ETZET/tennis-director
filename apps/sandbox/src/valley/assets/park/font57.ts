/** 一行字有几格宽（字 5 格 + 字间 1 格；空格 3 格） */
export const width57 = (text: string): number =>
  [...text].reduce((a, c, i) => a + (c === ' ' ? 3 : 5) + (i < text.length - 1 ? 1 : 0), 0);

/**
 * 一行字的竖条（同一个字同一列连续的格并成一条）：[列 0, 列 1, 行 0, 行 1]，列从左数、行从字底往上数（0..7）
 */
export function cells57(text: string): [number, number, number, number][] {
  const out: [number, number, number, number][] = [];
  let cx = 0;
  for (const ch of text) {
    if (ch === ' ') {
      cx += 4;
      continue;
    }
    const g = FONT57[ch];
    if (g)
      for (let c = 0; c < 5; c++) {
        let r = 0;
        while (r < 7) {
          if (g[r][c] !== '#') {
            r++;
            continue;
          }
          let e = r;
          while (e < 7 && g[e][c] === '#') e++;
          out.push([cx + c, cx + c + 1, 7 - e, 7 - r]);
          r = e;
        }
      }
    cx += 6;
  }
  return out;
}
