// 两款车的尺寸（米，车的本地坐标：车头朝 −z，x 车宽，y 朝上，原点 = 落地点中心）。
// 设计纹素 0.09 米：最细的东西（B 柱、车顶行李架、反光条）2 纹素，车灯 2 纹素高。
// 1× 下（0.045 米/纹素）轿车朝北 42 × 94 纹素、朝西 100 × 52 纹素（规格 clubpark.md：1.9 × 1.45 × 4.5 / SUV 2.0 × 1.8 × 4.8）。

export interface VehicleSpec {
  kind: 'car' | 'suv';
  /** 侧板（盖面）在 x = ±halfW；下半车身的倒角 */
  halfW: number;
  bevel: number;
  /** 侧板外形 [z, y]（顶、车头车尾、底再往外长 bevel）；轮拱是底边上的缺口 */
  profile: [number, number][];
  /** 轮子：半径、胎宽、前后轴 z、胎外侧往里缩多少 */
  wheel: { r: number; w: number; z: [number, number]; inset: number };
  /** 玻璃舱：下沿（y、[z0, z1]、半宽）和上沿；pillars = 漆面柱子的 [z0, z1]（要落在上下沿都有的那段 z 里） */
  cabin: {
    yb: number;
    zb: [number, number];
    hwb: number;
    yt: number;
    zt: [number, number];
    hwt: number;
    pillars: [number, number][];
  };
  /** 车顶板：下环 [半宽, z0, z1] @ y0，上环 @ y1（上环收进去 = 车顶四周一圈倒角，亮边就在这） */
  roof: { y0: number; lo: [number, number, number]; y1: number; hi: [number, number, number] };
  /** 车窗反光条：侧窗每段一条（下沿起点 z、宽、上沿往前斜多少）；后窗 / 前挡一条（x 起点、宽、斜） */
  glints: { side: [number, number, number][]; rear: [number, number, number]; front: [number, number, number] };
  /** 车灯（y0, y1, 内侧 x, 包到侧面多深），保险杠（y0, y1, 伸出多少） */
  head: [number, number, number, number];
  tail: [number, number, number, number];
  bumper: [number, number, number];
  /** 车头、车尾外沿 z（含倒角） */
  nose: number;
  rear: number;
  /** 前门：铰链 z（前沿）、后沿 z、门板 y0..y1、门窗上沿 */
  door: { z0: number; z1: number; y0: number; y1: number; yw: number };
  /** SUV：车顶行李架（x 中心、y0、y1、z0、z1）、备胎（半径、厚、中心 y） */
  rails?: [number, number, number, number, number];
  spare?: [number, number, number];
}

