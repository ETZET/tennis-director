// 纯数据（规则 clubsim-is-pure：只 import cast/types、./types、../world）。x / z 是世界坐标（米），只用来估路上走多久；
// 每个人具体站哪、朝哪、什么姿势在 clubwalk/sim/spots.ts（个数 = cap，spots.test.ts 守着）。
// 容量照场景里实际摆的东西数（clubwalk/sim/spots.ts 的注释写了出处）：长椅 2 个座、长桌半张 4 个座、躺椅一张一个……
//
// id 的写法：<场景>.<地点>[.<哪一个>]；员工的岗位 'post.<场景>.<岗位>'，员工休息处 'staff.<哪里>'。
// 约定（引擎读）：
// - for 里的 'staff' = 所有固定岗位的人（cast 的 role staff / vendor / coach / pro；types.ts 的 for 没有 'vendor'）。
// - 吃的、喝的都是 stall（cap 1 的窗口 + 6 个人的队，点完单去 table 坐着吃）；doing 'order' = 要摊主（needs），
//   doing 'drink' = 自助的饮水点（不要人、不排长队，渴了顺路喝一口）。会所的 cafe 也是窗口（点完去 house.cafe.t* 或拿着走）。
// - 酒吧（bar）是坐下来就有人招呼：吧凳和高脚桌就是 cap，要酒保在岗。
// - 场地（court / pickle）party：一伙人占一块；匹克球有拍架边的队（等场），网球场没有（满了就去别处）。
// - 中心球场的场地不对会员开放（表演赛 = 职业球员的岗位 post.stadium.pros）；会员、客人坐看台看。
import type { Minute, Place, PlaceId } from './types';

const h = (hh: number, mm = 0): Minute => hh * 60 + mm;
/** 摊主的营业时间（club-sim.md：摊主 10:00–21:00） */
const STALL_OPEN: [Minute, Minute] = [h(10), h(21)];
/** 会所咖啡吧（早班咖啡师 6:30 开门准备） */
const CAFE_OPEN: [Minute, Minute] = [h(6, 30), h(19)];
/** 二楼酒吧（中午开到关门） */
const BAR_OPEN: [Minute, Minute] = [h(11), h(22)];
/** 有日光才开的（泳池、高尔夫） */
const POOL_OPEN: [Minute, Minute] = [h(7), h(20)];
const GOLF_OPEN: [Minute, Minute] = [h(6), h(18, 30)];
/** 店（专卖、纪念品、穿线、便利） */
const SHOP_OPEN: [Minute, Minute] = [h(8), h(20)];

const STAFF = ['staff'] as const;
const KID = ['kid'] as const;

/** 员工的岗位 */
const post = (
  id: PlaceId,
  scene: Place['scene'],
  name: string,
  x: number,
  z: number,
  cap = 1,
  extra: Partial<Place> = {},
): Place => ({
  id,
  scene,
  kind: 'post',
  name,
  x,
  z,
  cap,
  doing: 'work',
  for: STAFF,
  ...extra,
});
/** 摊位窗口：一人点单 1–3 分钟，排 6 个，要摊主在岗 */
const stall = (id: PlaceId, name: string, x: number, z: number, needs: PlaceId, extra: Partial<Place> = {}): Place => ({
  id,
  scene: 'clubfood',
  kind: 'stall',
  name,
  x,
  z,
  cap: 1,
  queue: 6,
  doing: 'order',
  needs,
  stay: [1, 3],
  open: STALL_OPEN,
  ...extra,
});
/** 自助饮水点：接一杯水 1–2 分钟，后面最多等 2 个 */
const water = (id: PlaceId, scene: Place['scene'], name: string, x: number, z: number): Place => ({
  id,
  scene,
  kind: 'stall',
  name,
  x,
  z,
  cap: 1,
  queue: 2,
  doing: 'drink',
  stay: [1, 2],
});
/** 长椅 / 场边座（坐着歇、看） */
const seat = (
  id: PlaceId,
  scene: Place['scene'],
  name: string,
  x: number,
  z: number,
  cap: number,
  extra: Partial<Place> = {},
): Place => ({ id, scene, kind: 'seat', name, x, z, cap, doing: 'rest', stay: [8, 30], ...extra });
const standSeat = (
  id: PlaceId,
  scene: Place['scene'],
  name: string,
  x: number,
  z: number,
  cap: number,
  extra: Partial<Place> = {},
): Place => ({ id, scene, kind: 'stand', name, x, z, cap, doing: 'watch', stay: [15, 60], ...extra });
const tennisCourt = (id: PlaceId, scene: Place['scene'], name: string, x: number, z: number): Place => ({
  id,
  scene,
  kind: 'court',
  name,
  x,
  z,
  cap: 4,
  doing: 'tennis',
  stay: [60, 90],
  party: true,
  for: ['member', 'guest', 'kid', 'parent', 'pro', 'coach'],
});
/** 一伙人一张的桌（吃 10–25 分钟） */
const foodTable = (id: PlaceId, name: string, x: number, z: number, extra: Partial<Place> = {}): Place => ({
  id,
  scene: 'clubfood',
  kind: 'table',
  name,
  x,
  z,
  cap: 4,
  doing: 'eat',
  stay: [10, 25],
  party: true,
  ...extra,
});

/** 凉棚长桌：三排（z −31.6 / −28.6 / −25.6）× 两张（x −34.1 / −28.9）× 西半 / 东半（clubfood/layout.ts TABLE_ROWS、TABLE_XS） */
const FOOD_TABLES: Place[] = [-31.6, -28.6, -25.6].flatMap((z, r) =>
  [-34.1, -28.9].flatMap((tx, k) =>
    [0, 1].map((half) => {
      const n = k * 2 + half + 1;
      const row = '北中南'[r];
      return foodTable(
        `food.table.${'abc'[r]}${n}`,
        `凉棚${row}排长桌 ${n}（${k === 0 ? '西' : '东'}桌${half === 0 ? '西' : '东'}半）`,
        tx + (half === 0 ? -1 : 1),
        z,
        { shade: true },
      );
    }),
  ),
);

