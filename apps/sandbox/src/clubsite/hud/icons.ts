/** 把字形（9×9）叠进心情泡的格子里 */
export function moodSprite(id: MoodId): Sprite {
  const g = MOODS[id].rows;
  const rows = BUBBLE.rows.map((r, y) => {
    const gy = y - 1;
    if (gy < 0 || gy >= g.length) return r;
    const chars = [...r];
    const gr = g[gy];
    for (let x = 0; x < gr.length; x++) if (gr[x] !== '.') chars[1 + x] = gr[x];
    return chars.join('');
  });
  return { rows };
}

