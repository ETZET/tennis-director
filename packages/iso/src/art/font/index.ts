export interface TextArtOptions {
  /** 字体，默认 '5x7' */
  font?: '5x7' | '3x5';
  /** 字色，默认白 */
  color?: string;
  /** 描边色（8 邻域一圈），默认深紫；传空字符串不描边 */
  outline?: string;
  /** 底色（圆角小牌子），不传就是透明 */
  bg?: string;
  /** 底色四周留的像素，默认有底色时 1、没有时 0 */
  pad?: number;
}

const FG = '1';
const OUT = '2';
const BG = '3';
/** 字间距、行间距（像素） */
const GAP = 1;
const LINE_GAP = 2;

/**
 * 给字符画加一圈描边：在笔画外侧（8 邻域或 4 邻域）的空格里填 `ch`，四周各扩 1 像素。
 * 图标也用它（4 邻域，和旧版画布描边一样）。
 */
export function ringOutline(rows: readonly string[], ch = 'O', diag = false): string[] {
  const h = rows.length;
  const w = Math.max(0, ...rows.map((r) => r.length));
  const on = (x: number, y: number) => y >= 0 && y < h && x >= 0 && x < w && (rows[y]?.[x] ?? '.') !== '.';
  const out: string[] = [];
  for (let y = -1; y <= h; y++) {
    let s = '';
    for (let x = -1; x <= w; x++) {
      if (on(x, y)) s += rows[y]?.[x] ?? '.';
      else {
        let near = on(x + 1, y) || on(x - 1, y) || on(x, y + 1) || on(x, y - 1);
        if (!near && diag) near = on(x + 1, y + 1) || on(x - 1, y + 1) || on(x + 1, y - 1) || on(x - 1, y - 1);
        s += near ? ch : '.';
      }
    }
    out.push(s);
  }
  return out;
}

/** 量一下字符串在某个字体下的宽高（不含描边和底色）；有不支持的字返回 null。 */
function layout(str: string, font: Readonly<Record<string, Glyph>>, upper: boolean): string[] | null {
  const lines = str.split('\n');
  const rendered: string[][] = [];
  for (const raw of lines) {
    const line = upper ? raw.toUpperCase() : raw;
    const glyphs: Glyph[] = [];
    for (const ch of line) {
      const g = font[ch];
      if (!g) return null;
      glyphs.push(g);
    }
    const h = Math.max(1, ...glyphs.map((g) => g.length));
    const rows: string[] = [];
    for (let y = 0; y < h; y++) {
      rows.push(glyphs.map((g) => (g[y] ?? '.'.repeat(g[0]?.length ?? 0)).replaceAll('#', FG)).join('.'.repeat(GAP)));
    }
    rendered.push(rows);
  }
  // 多行居中排
  const w = Math.max(...rendered.map((r) => r[0]?.length ?? 0));
  const out: string[] = [];
  rendered.forEach((rows, i) => {
    if (i > 0) for (let k = 0; k < LINE_GAP; k++) out.push('.'.repeat(w));
    for (const r of rows) {
      const left = Math.floor((w - r.length) / 2);
      out.push('.'.repeat(left) + r + '.'.repeat(w - r.length - left));
    }
  });
  return out;
}

/**
 * 把一段字排成一张像素图（纯函数，可以在 node 里测）。
 * 锚点在底边中间（漫画字、招牌按这个点贴到世界坐标的投影点上）。
 * 支持 '\n' 换行（各行居中）；字体里没有的字（例如中文）返回 null。
 */
export function textArt(str: string, o: TextArtOptions = {}): PixelArt | null {
  const small = o.font === '3x5';
  let rows = layout(str, small ? FONT3x5 : FONT5x7, small);
  if (!rows || str.length === 0) return null;
  const outline = o.outline ?? '#2a2238';
  if (outline) rows = ringOutline(rows, OUT, true);
  const pal: Record<string, string> = { [FG]: o.color ?? '#ffffff' };
  if (outline) pal[OUT] = outline;
  if (o.bg) {
    const pad = o.pad ?? 1;
    const w = (rows[0]?.length ?? 0) + pad * 2;
    const blank = BG.repeat(w);
    const mid = rows.map((r) => BG.repeat(pad) + r.replaceAll('.', BG) + BG.repeat(pad));
    rows = [...Array<string>(pad).fill(blank), ...mid, ...Array<string>(pad).fill(blank)];
    // 圆角：四个角各挖掉一个像素
    const cut = (r: string) => `.${r.slice(1, -1)}.`;
    rows[0] = cut(rows[0] ?? '');
    rows[rows.length - 1] = cut(rows[rows.length - 1] ?? '');
    pal[BG] = o.bg;
  } else if (o.pad) {
    const w = (rows[0]?.length ?? 0) + o.pad * 2;
    const blank = '.'.repeat(w);
    const pad = '.'.repeat(o.pad);
    rows = [
      ...Array<string>(o.pad).fill(blank),
      ...rows.map((r) => pad + r + pad),
      ...Array<string>(o.pad).fill(blank),
    ];
  }
  const w = rows[0]?.length ?? 0;
  return { rows, ox: Math.floor(w / 2), oy: rows.length - 1, pal };
}
