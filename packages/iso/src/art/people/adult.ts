import type { ArtAnim, Facing, PixelArt } from '../format';

/**
 * 成人精灵表：移动、基础姿势、击球分段（ADR 0019，契约见 docs/design/iso-architecture.md）。
 *
 * 约定（详见同目录 README.md）：
 * - 身体 8×14（含描边）：头 5 行、躯干 3 行、下装 2 行、腿 1 行、鞋 1 行；和 gestures.ts 的底身同形，切换手势不跳。
 * - 每帧裁到包围盒，宽高各不相同；锚点 (ox, oy) = 两脚中间、鞋底下面那一行描边。身体左右对称于第 ox-1 列和第 ox 列之间，
 *   所以水平翻转时用 ox' = 宽 - ox（不是 宽 - 1 - ox），人不会左右跳一格。
 * - front：脸朝镜头（画面右下），右手在画面左边；back：背朝镜头（画面右上），右手在画面右边。朝左由运行时翻转。
 * - 挂点：hand_r、hand_l、head_top（头顶描边那一格，头的中线偏右）、racket（拍面中心；只在能拿拍子的帧上有）。
 * - 头顶两行用帽子槽 C：没戴帽子时运行时把 C 设成发色。
 * - 球拍只用 Q，而且只画在空格或手边的自动描边上，从不压身体：没拿拍子时 Q = 'none'，不会留洞。
 * - 1、2、3 是道具固定色（手机壳、手机屏、夹板）。
 *
 * 这些帧由一个拼帧脚本生成后再手修，之后可以由像素美术逐张替换；改的时候保持锚点和挂点的含义。
 */

const PAL: Readonly<Record<string, string>> = { '1': '#3a3d4a', '2': '#d8f4ff', '3': '#a8743c' };

function f(ox: number, oy: number, pts: Record<string, readonly [number, number]>, rows: readonly string[]): PixelArt {
  return { rows, ox, oy, pts, pal: PAL };
}

